function MarqueeStrip() {
    const items = [...marqueeLogos, ...marqueeLogos, ...marqueeLogos, ...marqueeLogos]
    return (
        <div className="relative py-4 overflow-hidden border-y border-[var(--border-color)] group cursor-default">
            <div className="flex items-center animate-marquee whitespace-nowrap group-hover:[animation-play-state:paused]">
                {items.map((logo, i) => (
                    <span
                        key={i}
                        className="inline-flex items-center mx-8 opacity-50 transition-all duration-300"
                        title={logo.name}
                        onMouseEnter={e => {
                            e.currentTarget.style.opacity = '1'
                            e.currentTarget.style.filter = `drop-shadow(0 0 8px ${logo.glow}) drop-shadow(0 0 20px ${logo.glow})`
                        }}
                        onMouseLeave={e => {
                            e.currentTarget.style.opacity = '0.5'
                            e.currentTarget.style.filter = 'none'
                        }}
                    >
                        {logo.svg}
                    </span>
                ))}
            </div>
        </div>
    )
}


